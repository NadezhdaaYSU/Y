  { unfold f32_exponent. change 255 with (Z.ones 8). rewrite Z.land_ones by lia.
    pose proof (Z.mod_pos_bound (Z.shiftr xb 23) (2 ^ 8) ltac:(lia)).
    change (2 ^ 8) with 256 in *. change (Z.ones 8) with 255. lia. }
  split; [exact He|].
  unfold f32_square. cbn [fst snd].
  set (frac := Z.land xb 8388607).

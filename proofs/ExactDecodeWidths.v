  { unfold frac. change 8388607 with (Z.ones 23). rewrite Z.land_ones by lia.
    apply Z.mod_pos_bound. lia. }
  assert (Hm : 0 <= (if f32_exponent xb =? 0 then frac else Z.lor frac 8388608) < 2 ^ 24).
  { destruct (f32_exponent xb =? 0).
    - split; [lia|]. apply Z.lt_trans with (2 ^ 23); [lia|]. reflexivity.
    - split; [apply Z.lor_nonneg; lia|].
      destruct (Z.eq_dec (Z.lor frac 8388608) 0) as [E0|N0]; [rewrite E0; reflexivity|].
      assert (Hpos : 0 < Z.lor frac 8388608)

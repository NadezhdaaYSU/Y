(** * The widths the exact decode path derives, and its integer functions.

    `python/y_lang/exact/` does not hard-code its integer widths. It derives
    them from the shapes: `model.act_levels_for` picks the activation width a
    linear layer's int32 accumulator can hold, `kv.k_levels_for` the K width a
    float32 score sum can hold, `attention.digit_width` the digit a float32
    `p.V` matmul can hold. Each bound in the Python is an `assert` on the
    result. This file transcribes the three functions and proves, for every
    input, that the width they return satisfies the bound the reduction needs.

    ** The tie to the Python.

    The definitions here are transcriptions. Two things hold them to the code:

    - [the_width_functions_return_what_the_python_returns]: on every sample
      in [ExactDecodeConstants.v], which is generated by running the Python,
      these definitions return the recorded value. 184 + 32 + 36 + 18 + 404
      samples, at and either side of every ceiling.
    - Not done yet: running these definitions against the Python on real
      activations, and the integer `exp2` over its whole domain against
      `attention.EXP2_DOMAIN_DIGEST`. Until then the samples are the tie.

    ** What is proved.

    - [the_derived_activation_width_fits_the_accumulator]: for every
      contraction length `k` where int8 itself fits (`k * 127 * 127 < 2^31`)
      and every requested width, `act_levels_for` returns `a` with
      `127 <= a`, `a + 1` a multiple of 128, and when `a > 127`,
      `k * (a + 128) * 127 < 2^31`: the bound `ExactLinear` asserts.
    - [the_derived_key_width_fits_float32]: for every head dimension where
      int8 K fits, `d * q * k_levels_for d q <= 2^24`.
    - [the_digit_width_fits_float32]: a nonzero `digit_width T lv` satisfies
      `T * (2^d - 1) * lv < 2^24`.
    - [the_two_digits_recombine], [the_high_digit_is_bounded],
      [the_high_digit_fits_int8]: `split_digits`.
    - [the_split_terms_fit_the_accumulator]: the `(a + 128)` in the bound is
      what the two digit products add up to, term by term.
    - [the_integer_exp_is_a_q28_weight]: `0 <= exp2 t <= 2^28` for every `t`.
    - [the_norm_fields_are_in_range]: the significand square and exponent
      `sum_of_squares` reads from a float32's bits are in the range
      [NormGridSum.v] assumes, for every 32-bit pattern.

    ** The refutations.

    - [dropping_the_128_admits_a_width_that_wraps]: without the `- 128` in
      `act_levels_for`, `k = 66051` would be given 255, and `k * (255 + 128)
      * 127` is past 2^31. With it the function returns 127.
    - [a_width_past_the_digit_ceiling_wraps_the_high_digit]: at 32767 the
      high digit is 255, outside int8.
    - [one_more_key_level_leaves_float32]: at head_dim 128 one more bit of K
      puts the score bound past 2^24.

    Checked with Rocq 9.1:  coqc -Q . "" ExactDecodeWidths.v  *)


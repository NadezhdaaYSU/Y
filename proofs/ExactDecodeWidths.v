(** ** Rounding a cap down to 2^n - 1                                   *)
(* ------------------------------------------------------------------ *)

(** Python's `int.bit_length`, which reads the magnitude of a negative. *)
Definition bit_length (z : Z) : Z := if z =? 0 then 0 else Z.log2 (Z.abs z) + 1.

(** `n = max(1, cap.bit_length()); if (1 << n) - 1 > cap: n -= 1;
     return max(127, (1 << n) - 1)`. *)
Definition floor_pow2m1 (cap : Z) : Z :=
  let n := Z.max 1 (bit_length cap) in
  let n := if cap <? 2 ^ n - 1 then n - 1 else n in
  Z.max 127 (2 ^ n - 1).

Lemma bit_length_spec : forall z, 0 < z ->
  2 ^ (bit_length z - 1) <= z < 2 ^ bit_length z /\ 1 <= bit_length z.
Proof.
  intros z Hz. unfold bit_length.
  destruct (Z.eqb_spec z 0); [lia|].
  rewrite Z.abs_eq by lia.
  pose proof (Z.log2_spec z Hz) as [L U].
  pose proof (Z.log2_nonneg z).
  replace (Z.log2 z + 1 - 1) with (Z.log2 z) by lia.
  replace (Z.log2 z + 1) with (Z.succ (Z.log2 z)) by lia. lia.
Qed.

Lemma bit_length_small : forall z b, 0 <= b -> Z.abs z < 2 ^ b -> bit_length z <= b.
Proof.
  intros z b Hb Hz. unfold bit_length.
  destruct (Z.eqb_spec z 0); [lia|].
  assert (0 < Z.abs z) by lia.
  assert (Z.log2 (Z.abs z) < b) by (apply Z.log2_lt_pow2; lia). lia.
Qed.

Lemma floor_pow2m1_ge : forall cap, 127 <= floor_pow2m1 cap.
Proof. intros. unfold floor_pow2m1. lia. Qed.

(** Above the int8 floor the result never exceeds the cap. The premise
    excludes caps below -128, which no caller forms. *)
Lemma floor_pow2m1_le : forall cap, -128 <= cap -> floor_pow2m1 cap <= Z.max 127 cap.
Proof.
  intros cap Hc. unfold floor_pow2m1.
  set (n0 := Z.max 1 (bit_length cap)).
  destruct (Z_lt_le_dec cap 127) as [Hsmall|Hbig].
  - (* the result is the floor: n ends at most 7 *)
    assert (Hn : (if cap <? 2 ^ n0 - 1 then n0 - 1 else n0) <= 7).
    { destruct (Z_lt_le_dec cap 0) as [Hneg|Hpos].
      - assert (bit_length cap <= 8) by (apply bit_length_small; lia).
        assert (1 <= 2 ^ n0) by (apply Z.pow_le_mono_r with (b := 0); lia).
        destruct (Z.ltb_spec cap (2 ^ n0 - 1)); lia.
      - assert (bit_length cap <= 7) by (apply bit_length_small; lia).
        destruct (Z.ltb_spec cap (2 ^ n0 - 1)); lia. }
    assert (Hn0 : 0 <= (if cap <? 2 ^ n0 - 1 then n0 - 1 else n0))
      by (destruct (Z.ltb_spec cap (2 ^ n0 - 1)); lia).
    assert (2 ^ (if cap <? 2 ^ n0 - 1 then n0 - 1 else n0) <= 2 ^ 7)
      by (apply Z.pow_le_mono_r; lia).
    change (2 ^ 7) with 128 in *. lia.
  - pose proof (bit_length_spec cap ltac:(lia)) as [[L U] B].
    assert (E : n0 = bit_length cap) by (unfold n0; lia). rewrite E.
    destruct (Z.ltb_spec cap (2 ^ bit_length cap - 1)); lia.
Qed.

Lemma pow2m1_shape : forall n, 0 <= n -> (Z.max 127 (2 ^ n - 1) + 1) mod 128 = 0.
Proof.
  intros n Hn. destruct (Z_lt_le_dec n 7) as [Hl|Hl].
  - assert (2 ^ n <= 2 ^ 6) by (apply Z.pow_le_mono_r; lia).
    change (2 ^ 6) with 64 in *. rewrite Z.max_l by lia. reflexivity.
  - assert (H7 : 2 ^ 7 <= 2 ^ n) by (apply Z.pow_le_mono_r; lia).
    change (2 ^ 7) with 128 in H7. rewrite Z.max_r by lia.
    replace (2 ^ n - 1 + 1) with (2 ^ n) by lia.
    assert (E : 2 ^ n = 2 ^ (n - 7) * 2 ^ 7).
    { rewrite <- Z.pow_add_r by lia. f_equal. lia. }
    rewrite E. change (2 ^ 7) with 128. apply Z.mod_mul. lia.
Qed.

Lemma floor_pow2m1_shape : forall cap, (floor_pow2m1 cap + 1) mod 128 = 0.
Proof.
  intros cap. unfold floor_pow2m1. apply pow2m1_shape.
  destruct (Z.ltb_spec cap (2 ^ Z.max 1 (bit_length cap) - 1)); lia.
Qed.

(* ------------------------------------------------------------------ *)
(** ** `model.act_levels_for`                                           *)
(* ------------------------------------------------------------------ *)

(** `cap = min(ACC_BUDGET // max(k * w_levels, 1) - 128, DIGIT_MAX, requested)`. *)
Definition act_levels_for (k w_levels requested : Z) : Z :=
  floor_pow2m1 (Z.min (Z.min (C.ACC_BUDGET / Z.max (k * w_levels) 1 - 128) C.DIGIT_MAX)
                      requested).

Theorem the_derived_activation_width_fits_the_accumulator : forall k requested,
  0 < k -> 0 <= requested ->
  k * 127 * 127 < C.ACC_BUDGET ->
  let a := act_levels_for k C.W_LEVELS requested in
  127 <= a <= Z.max 127 (Z.min C.DIGIT_MAX requested)
  /\ (a + 1) mod 128 = 0
  /\ (127 < a -> k * (a + 128) * 127 < C.ACC_BUDGET).
Proof.
  intros k requested Hk Hreq Hint8 a.
  unfold C.ACC_BUDGET, C.W_LEVELS, C.DIGIT_MAX in *.
  set (x := k * 127) in *.
  assert (Hx : 0 < x) by (unfold x; lia).
  assert (Hdiv : 0 <= 2147483648 / x) by (apply Z.div_pos; lia).
  set (cap := Z.min (Z.min (2147483648 / Z.max x 1 - 128) 16383) requested).
  assert (Ea : a = floor_pow2m1 cap) by reflexivity.
  assert (Hmax : Z.max x 1 = x) by lia.
  assert (Hcap : -128 <= cap) by (unfold cap; rewrite Hmax; lia).
  pose proof (floor_pow2m1_le cap Hcap) as Hle.
  pose proof (floor_pow2m1_ge cap) as Hge.
  repeat split.
  - lia.
  - rewrite Ea. unfold cap in *. lia.
  - rewrite Ea. apply floor_pow2m1_shape.
  - intros Hwide. rewrite Ea in *.
    assert (Hq : floor_pow2m1 cap + 128 <= 2147483648 / x)
      by (unfold cap in *; rewrite Hmax in *; lia).
    pose proof (Z.mul_div_le 2147483648 x Hx) as Hmd.
    assert (Hprod : x * (floor_pow2m1 cap + 128) <= 2147483648) by nia.
    assert (Hodd : forall m, 127 * m <> 2147483648) by (intros m; lia).
    specialize (Hodd (k * (floor_pow2m1 cap + 128))).
    unfold x in *. nia.
Qed.

(** What the `- 128` is for: the two digit products are accumulated
    interleaved, so the bound is on `a + 128`, not on `a`. *)
Definition act_levels_without_the_128 (k requested : Z) : Z :=
  floor_pow2m1 (Z.min (Z.min (C.ACC_BUDGET / Z.max (k * C.W_LEVELS) 1) C.DIGIT_MAX) requested).

Theorem dropping_the_128_admits_a_width_that_wraps :
  act_levels_without_the_128 66051 255 = 255
  /\ C.ACC_BUDGET <= 66051 * (255 + 128) * 127
  /\ act_levels_for 66051 C.W_LEVELS 255 = 127
  /\ 66051 * 127 * 127 < C.ACC_BUDGET.
Proof. repeat split; vm_compute; try reflexivity; discriminate. Qed.

(* ------------------------------------------------------------------ *)
(** ** `kv.k_levels_for`                                                *)
(* ------------------------------------------------------------------ *)

(** `cap = min(SCORE_BUDGET // max(d * q_levels, 1), K_LEVELS)`. *)
Definition k_levels_for (d q_levels : Z) : Z :=
  floor_pow2m1 (Z.min (C.SCORE_BUDGET / Z.max (d * q_levels) 1) C.K_LEVELS).

Theorem the_derived_key_width_fits_float32 : forall d q,
  0 < d -> 0 < q ->
  d * q * 127 <= C.SCORE_BUDGET ->
  let kl := k_levels_for d q in
  127 <= kl <= Z.max 127 C.K_LEVELS /\ d * q * kl <= C.SCORE_BUDGET.
Proof.
  intros d q Hd Hq Hint8 kl.
  unfold C.SCORE_BUDGET, C.K_LEVELS in *.
  set (x := d * q) in *.
  assert (Hx : 0 < x) by (unfold x; nia).
  assert (Hdiv : 0 <= 16777216 / x) by (apply Z.div_pos; lia).
  set (cap := Z.min (16777216 / Z.max x 1) 1023).
  assert (Ek : kl = floor_pow2m1 cap) by reflexivity.
  assert (Hmax : Z.max x 1 = x) by lia.
  assert (Hcap : -128 <= cap) by (unfold cap; rewrite Hmax; lia).
  pose proof (floor_pow2m1_le cap Hcap) as Hle.
  pose proof (floor_pow2m1_ge cap) as Hge.
  rewrite Ek.
  assert (G2 : floor_pow2m1 cap <= Z.max 127 1023) by (unfold cap in *; lia).
  assert (G3 : x * floor_pow2m1 cap <= 16777216).
  { destruct (Z_le_gt_dec (floor_pow2m1 cap) 127) as [H127|Hwide].
    - assert (E127 : floor_pow2m1 cap = 127) by lia. rewrite E127. lia.
    - assert (Hq' : floor_pow2m1 cap <= 16777216 / x)
        by (unfold cap in *; rewrite Hmax in *; lia).
      pose proof (Z.mul_div_le 16777216 x Hx). nia. }
  repeat split; lia.
Qed.

Theorem one_more_key_level_leaves_float32 :
  k_levels_for 128 127 = 1023
  /\ 128 * 127 * 1023 <= C.SCORE_BUDGET
  /\ C.SCORE_BUDGET < 128 * 127 * 2047.
Proof. repeat split; vm_compute; try reflexivity; discriminate. Qed.

(* ------------------------------------------------------------------ *)
(** ** `attention.digit_width`                                          *)
(* ------------------------------------------------------------------ *)

Definition digit_fits (T lv d : Z) : bool := T * (2 ^ d - 1) * lv <? C.SCORE_BUDGET.

(** `dbits = 8; while dbits > 0 and T * ((1 << dbits) - 1) * lv >= 2^24: dbits -= 1`. *)
Definition digit_width (T lv : Z) : Z :=
  if digit_fits T lv 8 then 8 else
  if digit_fits T lv 7 then 7 else
  if digit_fits T lv 6 then 6 else
  if digit_fits T lv 5 then 5 else
  if digit_fits T lv 4 then 4 else
  if digit_fits T lv 3 then 3 else
  if digit_fits T lv 2 then 2 else
  if digit_fits T lv 1 then 1 else 0.

Theorem the_digit_width_fits_float32 : forall T lv,
  let d := digit_width T lv in
  0 <= d <= 8 /\ (0 < d -> T * (2 ^ d - 1) * lv < C.SCORE_BUDGET).
Proof.
  intros T lv d. unfold d, digit_width, digit_fits.
  repeat match goal with
  | |- context [?a <? ?b] => destruct (Z.ltb_spec a b)
  end; split; try lia; intros _; assumption.
Qed.

(* ------------------------------------------------------------------ *)
(** ** `model.split_digits`                                             *)
(* ------------------------------------------------------------------ *)

(** `(q >> 7, q & 127)`. *)
Definition split_hi (q : Z) : Z := Z.shiftr q 7.
Definition split_lo (q : Z) : Z := Z.land q 127.

Lemma split_hi_div : forall q, split_hi q = q / 128.
Proof. intros. unfold split_hi. rewrite Z.shiftr_div_pow2 by lia. reflexivity. Qed.

Lemma split_lo_mod : forall q, split_lo q = q mod 128.
Proof.
  intros. unfold split_lo. change 127 with (Z.ones 7).
  rewrite Z.land_ones by lia. reflexivity.
Qed.

Theorem the_two_digits_recombine : forall q,
  split_hi q * 128 + split_lo q = q /\ 0 <= split_lo q <= 127.
Proof.
  intros q. rewrite split_hi_div, split_lo_mod.
  pose proof (Z.div_mod q 128 ltac:(lia)).
  pose proof (Z.mod_pos_bound q 128 ltac:(lia)). lia.
Qed.

Theorem the_high_digit_is_bounded : forall a q,
  0 <= a -> (a + 1) mod 128 = 0 -> Z.abs q <= a ->
  Z.abs (128 * split_hi q) <= a + 1.
Proof.
  intros a q Ha Hm Hq. rewrite split_hi_div.
  pose proof (Z.div_mod (a + 1) 128 ltac:(lia)) as Da. rewrite Hm in Da.
  pose proof (Z.div_mod q 128 ltac:(lia)) as Dq.
  pose proof (Z.mod_pos_bound q 128 ltac:(lia)) as Bq.
  assert (- ((a + 1) / 128) <= q / 128).
  { apply Z.div_le_lower_bound; lia. }
  lia.
Qed.

Theorem the_high_digit_fits_int8 : forall q,
  Z.abs q <= C.DIGIT_MAX -> -128 <= split_hi q <= 127.
Proof.
  intros q Hq. unfold C.DIGIT_MAX in Hq. rewrite split_hi_div.
  split.
  - apply Z.div_le_lower_bound; lia.
  - assert (q / 128 < 128) by (apply Z.div_lt_upper_bound; lia). lia.
Qed.

Theorem a_width_past_the_digit_ceiling_wraps_the_high_digit :
  split_hi 32767 = 255 /\ 127 < 255 /\ C.DIGIT_MAX < 32767.
Proof. repeat split; vm_compute; reflexivity. Qed.

(** The `(a + 128)` of `ExactLinear`'s bound, term by term: with `q` at most
    `a` and the weight at most `w`, the two digit products of one position
    have magnitudes that sum to at most `(a + 128) * w`. *)
Theorem the_split_terms_fit_the_accumulator : forall a w q x,
  0 <= a -> (a + 1) mod 128 = 0 -> Z.abs q <= a -> Z.abs x <= w ->
  Z.abs (128 * split_hi q * x) + Z.abs (split_lo q * x) <= (a + 128) * w.
Proof.
  intros a w q x Ha Hm Hq Hx.
  pose proof (the_high_digit_is_bounded a q Ha Hm Hq) as Hh.
  destruct (the_two_digits_recombine q) as [_ Hl].
  rewrite !Z.abs_mul. rewrite Z.abs_mul in Hh.
  assert (Z.abs (split_lo q) <= 127) by lia.
  assert (0 <= Z.abs x) by lia.
  assert (0 <= Z.abs (split_hi q)) by lia.
  nia.
Qed.

(* ------------------------------------------------------------------ *)
(** ** `attention.exp2_neg_q16_16`                                      *)
(* ------------------------------------------------------------------ *)

(** `2^-t` for Q16.16 `t`, as a Q0.28 integer. Transcribed line for line;
    the Python runs it in int64, where no intermediate reaches 2^61. *)
Definition exp2_neg_q16_16 (t0 : Z) : Z :=
  let t := Z.max t0 0 in
  let n := Z.shiftr t 16 in
  let f := Z.land t 65535 in
  let idx := Z.min (Z.max (Z.shiftr f 10) 0) 63 in
  let base := nth (Z.to_nat idx) C.EXP_TABLE 0 in
  let d := Z.land f 1023 in
  let y := Z.shiftr (d * C.LN2_Q30) 16 in
  let y2 := Z.shiftr (y * y) 30 in
  let y3 := Z.shiftr (y2 * y) 30 in
  let y3o6 := Z.shiftr (y3 * C.RECIP6_Q32) 32 in
  let corr := 2 ^ 30 - y + Z.shiftr y2 1 - y3o6 in
  let g := Z.shiftr (base * corr) 30 in
  let sh := Z.min (2 + n) 62 in
  let out := Z.shiftr (g + Z.shiftl 1 (sh - 1)) sh in
  if 30 <=? n then 0 else out.

Lemma exp_table_in_range : Forall (fun b => 0 <= b <= 2 ^ 30) C.EXP_TABLE.
Proof.
  apply Forall_forall. intros b Hb.
  assert (H : forallb (fun b => (0 <=? b) && (b <=? 2 ^ 30)) C.EXP_TABLE = true)
    by (vm_compute; reflexivity).
  rewrite forallb_forall in H. specialize (H b Hb).
  apply andb_true_iff in H. destruct H as [H1 H2].
  apply Z.leb_le in H1. apply Z.leb_le in H2. lia.
Qed.

Lemma exp_table_nth : forall i, 0 <= nth i C.EXP_TABLE 0 <= 2 ^ 30.
Proof.
  intros i. destruct (Nat.lt_ge_cases i (length C.EXP_TABLE)) as [H|H].
  - pose proof exp_table_in_range as F. rewrite Forall_forall in F.
    apply F, nth_In, H.
  - rewrite nth_overflow by exact H. lia.
Qed.

Lemma shiftr_bounds : forall a s, 0 <= a -> 0 <= s -> 0 <= Z.shiftr a s <= a.
Proof.
  intros a s Ha Hs. rewrite Z.shiftr_div_pow2 by lia.
  assert (0 < 2 ^ s) by (apply Z.pow_pos_nonneg; lia).
  split; [apply Z.div_pos; lia|].
  apply Z.div_le_upper_bound; [lia|]. nia.
Qed.

Lemma shiftr_mul_le : forall a b s, 0 <= a -> 0 <= b <= 2 ^ s -> 0 <= s ->
  0 <= Z.shiftr (a * b) s <= a.
Proof.
  intros a b s Ha Hb Hs. rewrite Z.shiftr_div_pow2 by lia.
  assert (0 < 2 ^ s) by (apply Z.pow_pos_nonneg; lia).
  split; [apply Z.div_pos; nia|].
  apply Z.div_le_upper_bound; [lia|]. nia.
Qed.

Theorem the_integer_exp_is_a_q28_weight : forall t,
  0 <= exp2_neg_q16_16 t <= 2 ^ 28.
Proof.
  intros t0. unfold exp2_neg_q16_16.
  set (t := Z.max t0 0).
  set (n := Z.shiftr t 16).
  set (f := Z.land t 65535).
  set (idx := Z.min (Z.max (Z.shiftr f 10) 0) 63).
  set (base := nth (Z.to_nat idx) C.EXP_TABLE 0).
  set (d := Z.land f 1023).
  set (y := Z.shiftr (d * C.LN2_Q30) 16).
  set (y2 := Z.shiftr (y * y) 30).
  set (y3 := Z.shiftr (y2 * y) 30).
  set (y3o6 := Z.shiftr (y3 * C.RECIP6_Q32) 32).
  set (corr := 2 ^ 30 - y + Z.shiftr y2 1 - y3o6).
  set (g := Z.shiftr (base * corr) 30).
  set (sh := Z.min (2 + n) 62).
  destruct (Z.leb_spec 30 n) as [Hn|Hn]; [lia|].
  assert (Ht : 0 <= t) by (unfold t; lia).
  assert (Hn0 : 0 <= n) by (unfold n; apply shiftr_bounds; lia).
  assert (Hd : 0 <= d <= 1023).
  { unfold d. change 1023 with (Z.ones 10). rewrite Z.land_ones by lia.
    pose proof (Z.mod_pos_bound f (2 ^ 10) ltac:(lia)).
    change (2 ^ 10) with 1024 in *. change (Z.ones 10) with 1023. lia. }
  assert (Hy : 0 <= y <= 2 ^ 24).
  { unfold y, C.LN2_Q30. rewrite Z.shiftr_div_pow2 by lia. split.
    - apply Z.div_pos; lia.
    - apply Z.div_le_upper_bound; [lia|].
      change (2 ^ 16 * 2 ^ 24) with 1099511627776. lia. }
  assert (Hy2 : 0 <= y2 <= y).
  { unfold y2. apply shiftr_mul_le; lia. }
  assert (Hy3 : 0 <= y3 <= y2).
  { unfold y3. apply shiftr_mul_le; lia. }
  assert (Hy36 : 0 <= y3o6 <= y3).
  { unfold y3o6. apply shiftr_mul_le; try lia. unfold C.RECIP6_Q32.
    change (2 ^ 32) with 4294967296. lia. }
  assert (Hh : 0 <= Z.shiftr y2 1 <= y2) by (apply shiftr_bounds; lia).
  assert (P24 : 2 ^ 24 = 16777216) by reflexivity.
  assert (P30 : 2 ^ 30 = 1073741824) by reflexivity.
  assert (Hcorr : 0 <= corr <= 2 ^ 30) by (unfold corr; lia).
  pose proof (exp_table_nth (Z.to_nat idx)) as Hbase. fold base in Hbase.
  assert (Hg : 0 <= g <= 2 ^ 30).
  { unfold g. rewrite Z.shiftr_div_pow2 by lia. split.
    - apply Z.div_pos; nia.
    - apply Z.div_le_upper_bound; [lia|]. nia. }
  assert (Hsh : 2 <= sh <= 62) by (unfold sh; lia).
  rewrite Z.shiftl_1_l. rewrite Z.shiftr_div_pow2 by lia.
  assert (Hp : 0 < 2 ^ sh) by (apply Z.pow_pos_nonneg; lia).
  assert (Hp1 : 0 < 2 ^ (sh - 1)) by (apply Z.pow_pos_nonneg; lia).
  assert (E1 : 2 ^ sh = 2 * 2 ^ (sh - 1)).
  { rewrite <- Z.pow_succ_r by lia. f_equal. lia. }
  assert (E2 : 2 ^ sh = 4 * 2 ^ (sh - 2)).
  { change 4 with (2 ^ 2). rewrite <- Z.pow_add_r by lia. f_equal. lia. }
  assert (Hp2 : 0 < 2 ^ (sh - 2)) by (apply Z.pow_pos_nonneg; lia).
  split.
  - apply Z.div_pos; lia.
  - assert (L : (g + 2 ^ (sh - 1)) / 2 ^ sh < 2 ^ 28 + 1).
    { apply Z.div_lt_upper_bound; [lia|].
      change (2 ^ 28) with 268435456. nia. }
    lia.
Qed.


        assert (Z.log2 frac < 23) by (apply Z.log2_lt_pow2; lia). lia. }
      change (Z.log2 8388608) with 23. lia. }
  set (m := if f32_exponent xb =? 0 then frac else Z.lor frac 8388608) in *.
  split; [|lia].

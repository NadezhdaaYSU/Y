(** The limbs of one square, at `s = max(e - p, 0)` binades below the row's
    largest: [NormGridSum.v]'s `hi` and `lo`, each in `[0, 2^40)`. *)
Definition norm_shift (e : Z) (xb : Z) : Z := Z.max (e - snd (f32_square xb)) 0.
Definition norm_hi (e xb : Z) : Z := NG.hi (fst (f32_square xb)) (norm_shift e xb).
Definition norm_lo (e xb : Z) : Z := NG.lo (fst (f32_square xb)) (norm_shift e xb).

Theorem the_norm_limbs_are_in_range : forall e xb,
  0 <= norm_hi e xb < 2 ^ 40 /\ 0 <= norm_lo e xb < 2 ^ 40.
Proof.
  intros e xb. destruct (the_norm_fields_are_in_range xb) as [_ [Hm _]].
  unfold norm_hi, norm_lo.
  pose proof (NG.limbs_bounded (fst (f32_square xb)) (norm_shift e xb) Hm
                ltac:(unfold norm_shift; lia)). tauto.
Qed.


(** ** The norm's fields                                                *)
(* ------------------------------------------------------------------ *)

(** `sum_of_squares` reads a float32's bits `xb` (as an int32): the biased
    exponent, the square of the 24-bit significand, and the square's exponent
    `p = 2 * max(ex, 1)`. *)
Definition f32_exponent (xb : Z) : Z := Z.land (Z.shiftr xb 23) 255.

Definition f32_square (xb : Z) : Z * Z :=
  let ex := f32_exponent xb in
  let frac := Z.land xb 8388607 in
  let m := if ex =? 0 then frac else Z.lor frac 8388608 in
  (m * m, 2 * Z.max ex 1).

Theorem the_norm_fields_are_in_range : forall xb,
  0 <= f32_exponent xb <= 255
  /\ 0 <= fst (f32_square xb) < 2 ^ 48
  /\ 2 <= snd (f32_square xb) <= 510.
Proof.
  intros xb.

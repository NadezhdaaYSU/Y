"""Write or check python/THIRD_PARTY_NOTICES: the licences of the crates
compiled into liby.so and ysu_gpu_probe, which the y-lang wheel ships.

    python3 tools/third_party_notices.py          # rewrite the file
    python3 tools/third_party_notices.py --check  # exit 1 if it is out of date

The crates are the ones `cargo tree -e normal` reports for the compiler on
x86_64 Linux: build and dev dependencies are not in the binaries. Each one's
licence text is copied from its source in the cargo registry (`--offline`).
Where a crate offers MIT, MIT is the licence taken and its text is the one
copied. A crate with no licence file is an error, not an omission.

The Rust standard library is in the binaries too. Its notice depends on the
toolchain, so `python/setup.py` copies the toolchain's own
`COPYRIGHT-library.html` into the wheel when it is built, rather than this
file carrying a copy that would go stale.
"""

import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "python" / "THIRD_PARTY_NOTICES"
TARGET = "x86_64-unknown-linux-gnu"
PACKAGE = "Y-compiler"

HEADER = """Third-party software in the y-lang wheel

liby.so and ysu_gpu_probe are compiled from Y (see LICENSE) and from the Rust
crates below, which keep their own licences. Where a crate is offered under
MIT or Apache-2.0, it is used under MIT. The Rust standard library's notice
is RUST_STD_COPYRIGHT.html beside liby.so.

Generated by tools/third_party_notices.py from Cargo.lock; do not edit.
"""


def cargo(*args):
    return subprocess.run(["cargo", *args, "--offline"], cwd=ROOT, check=True,
                          capture_output=True, text=True).stdout


def linked_crates():
    out = cargo("tree", "-e", "normal", "--prefix", "none", "--format", "{p}|{l}",
                "-p", PACKAGE, "--target", TARGET)
    crates = {}
    for line in out.splitlines():
        spec, _, licence = line.partition("|")
        name, version = spec.split()[:2]
        if name == PACKAGE:
            continue
        crates[(name, version.lstrip("v"))] = licence.replace(" (*)", "").strip()
    return crates


def licence_text(name, directory, licence):
    files = sorted(f for f in os.listdir(directory)
                   if f.upper().startswith(("LICENSE", "LICENCE", "COPYING")))
    if "MIT" in licence.split() and "LICENSE-MIT" in files:
        chosen = ["LICENSE-MIT"]
    elif "LICENSE" in files:
        chosen = ["LICENSE"]
    else:
        chosen = files
    if not chosen:
        raise SystemExit(f"{name}: no licence file in {directory}")
    return "\n".join((Path(directory) / f).read_text(encoding="utf-8").strip() + "\n"
                     for f in chosen)


def render():
    crates = linked_crates()
    meta = json.loads(cargo("metadata", "--format-version", "1"))
    dirs = {(p["name"], p["version"]): os.path.dirname(p["manifest_path"])
            for p in meta["packages"]}
    parts = [HEADER]
    for (name, version), licence in sorted(crates.items()):
        if (name, version) not in dirs:
            raise SystemExit(f"{name} {version}: not in `cargo metadata`")
        parts.append(f"\n{'=' * 78}\n{name} {version}\nLicence: {licence}\n"
                     f"Source: https://crates.io/crates/{name}/{version}\n{'=' * 78}\n\n")
        parts.append(licence_text(name, dirs[(name, version)], licence))
    return "".join(parts)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/third_party_notices.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
